import { promises as fs } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { afterEach, describe, expect, it, vi } from 'vitest'
import chokidar from 'chokidar'
import ts from 'typescript'
import { generateExports } from '../src/main'
import { isSameFilePath } from './fs-path'

const directories: string[] = []
const watchers: ReturnType<typeof chokidar.watch>[] = []
afterEach(async () => {
  await Promise.all(watchers.splice(0).map((watcher) => watcher.close()))
  vi.restoreAllMocks()
  await Promise.all(
    directories
      .splice(0)
      .map((directory) => fs.rm(directory, { recursive: true, force: true })),
  )
})

async function tree(files: Record<string, string>) {
  const directory = await fs.mkdtemp(join(tmpdir(), 'generate-exports-'))
  directories.push(directory)
  for (const [file, content] of Object.entries(files)) {
    const target = join(directory, file)
    await fs.mkdir(resolve(target, '..'), { recursive: true })
    await fs.writeFile(target, content)
  }
  return directory
}

async function content(file: string, includes?: string) {
  let result = ''
  await vi.waitFor(
    async () => {
      result = await fs.readFile(file, 'utf8')
      if (includes) expect(result).toContain(includes)
      else expect(result).toContain('/* End of auto-generated content. */')
    },
    { timeout: 4000, interval: 20 },
  )
  return result
}

const header =
  '/**\n * This file is auto-generated by GenerateExportsWebpackPlugin.\n * Check this file into source control.\n * Do not edit this file.\n */\n'
const footer = '\n/* End of auto-generated content. */\n'
const syntaxErrors = (text: string) =>
  (
    ts.createSourceFile(
      'index.ts',
      text,
      ts.ScriptTarget.ESNext,
      true,
    ) as ts.SourceFile & { parseDiagnostics: unknown[] }
  ).parseDiagnostics

describe('generate-exports real filesystem generation', () => {
  it('writes sorted default barrels, excludes its own output and is repeatable', async () => {
    const directory = await tree({
      'zebra.ts': 'export default 1',
      'alpha.ts': 'export default 2',
      'index.ts': 'stale',
    })
    const generator = generateExports({
      entries: [
        { directories: [directory], include: ['*.ts'], filename: 'index.ts' },
      ],
    })
    expect(generator.name).toBe('generate-exports')
    expect(generator.start()).toBeUndefined()
    const expected =
      header +
      "export { default as alpha } from './alpha';\nexport { default as zebra } from './zebra';" +
      footer
    expect(await content(join(directory, 'index.ts'))).toBe(expected)
    generator.start()
    expect(await content(join(directory, 'index.ts'))).toBe(expected)
  })

  it('honors nested glob exclusions and uses POSIX relative module specifiers', async () => {
    const directory = await tree({
      'nested/value.ts': '',
      'value.spec.ts': '',
      'ignored/private.ts': '',
      'keep.ts': '',
      '.hidden.ts': '',
    })
    generateExports({
      entries: [
        {
          directories: [directory],
          include: ['**/*.ts'],
          exclude: ['**/*.spec.ts', 'ignored/**'],
          filename: 'index.ts',
        },
      ],
    }).start()
    expect(await content(join(directory, 'index.ts'))).toBe(
      header +
        "export { default as keep } from './keep';\nexport { default as value } from './nested/value';" +
        footer,
    )
  })

  it('generates executable default public barrels from real ES modules', async () => {
    const directory = await tree({
      'two.mjs': 'export default { value: 2 }',
      'one.mjs': 'export default 1',
    })
    generateExports({
      entries: [
        {
          directories: [directory],
          include: ['*.mjs'],
          filename: 'index.mjs',
          omitExtension: false,
        },
      ],
    }).start()
    const output = await content(join(directory, 'index.mjs'))
    expect(output).toContain("export { default as one } from './one.mjs';")
    const barrel = await import(
      /* @vite-ignore */ pathToFileURL(join(directory, 'index.mjs')).href
    )
    expect(Object.keys(barrel)).toEqual(['one', 'two'])
    expect(barrel.one).toBe(1)
    expect(barrel.two).toEqual({ value: 2 })
  })

  it('supports namespace and unaliased wildcard exports with executable public barrels', async () => {
    const directory = await tree({
      'alpha.mjs': 'export const value = 3; export default 8',
    })
    generateExports({
      entries: [
        {
          directories: [directory],
          include: ['alpha.mjs'],
          filename: 'namespace.mjs',
          exportAll: true,
          omitExtension: false,
        },
      ],
    }).start()
    expect(await content(join(directory, 'namespace.mjs'))).toContain(
      "export * as alpha from './alpha.mjs';",
    )
    const namespace = await import(
      /* @vite-ignore */ pathToFileURL(join(directory, 'namespace.mjs')).href
    )
    expect(namespace.alpha.value).toBe(3)
    expect(namespace.alpha.default).toBe(8)
    generateExports({
      entries: [
        {
          directories: [directory],
          include: ['alpha.mjs'],
          filename: 'wildcard.mjs',
          exportAll: true,
          exportAllAsAlias: false,
          omitExtension: false,
        },
      ],
    }).start()
    expect(await content(join(directory, 'wildcard.mjs'))).toContain(
      "export * from './alpha.mjs';",
    )
    const wildcard = await import(
      /* @vite-ignore */ pathToFileURL(join(directory, 'wildcard.mjs')).href
    )
    expect(wildcard.value).toBe(3)
    expect(wildcard.default).toBeUndefined()
  })

  it('applies per-directory overrides without leaking them to sibling directories or entries', async () => {
    const a = await tree({ 'alpha.ts': '' })
    const b = await tree({ 'beta.ts': '' })
    const c = await tree({ 'gamma.ts': '' })
    generateExports({
      entries: [
        {
          directories: [
            [
              a,
              {
                include: ['*.ts'],
                filename: 'custom.ts',
                singleQuote: false,
                omitSemi: true,
                omitExtension: false,
                exportAll: true,
                exportAllAsAlias: false,
              },
            ],
            b,
          ],
          include: ['*.ts'],
          filename: 'index.ts',
        },
        { directories: [c], include: ['*.ts'], filename: 'other.ts' },
      ],
    }).start()
    expect(await content(join(a, 'custom.ts'))).toBe(
      header + 'export * from "./alpha.ts"' + footer,
    )
    expect(await content(join(b, 'index.ts'))).toBe(
      header + "export { default as beta } from './beta';" + footer,
    )
    expect(await content(join(c, 'other.ts'))).toBe(
      header + "export { default as gamma } from './gamma';" + footer,
    )
  })

  it('resolves relative directory paths against the working directory', async () => {
    const directory = await tree({ 'value.ts': '' })
    const relative = (await import('node:path')).relative(
      process.cwd(),
      directory,
    )
    generateExports({
      entries: [{ directories: [relative], include: ['*.ts'] }],
    }).start()
    expect(await content(join(directory, 'index.js'))).toBe(
      header + "export { default as value } from './value';" + footer,
    )
  })

  it('creates nested output directories and handles no matches or empty configuration', async () => {
    const directory = await tree({ 'not-included.txt': 'untouched' })
    generateExports({
      entries: [
        {
          directories: [directory],
          filename: 'generated/index.js',
          include: ['*.ts'],
        },
      ],
    }).start()
    expect(await content(join(directory, 'generated/index.js'))).toBe(
      header + footer,
    )
    expect(await fs.readFile(join(directory, 'not-included.txt'), 'utf8')).toBe(
      'untouched',
    )
    expect(generateExports({ entries: [] }).start()).toBeUndefined()
    expect(
      generateExports({ entries: [{ directories: [] }] }).start(),
    ).toBeUndefined()
  })

  it('uses empty include defaults rather than exporting unrelated files', async () => {
    const directory = await tree({ 'value.ts': 'export default 1' })
    generateExports({ entries: [{ directories: [directory] }] }).start()
    expect(await content(join(directory, 'index.js'))).toBe(header + footer)
  })

  it('does not rewrite identical output or alter its modification time', async () => {
    const expected =
      header + "export { default as alpha } from './alpha';" + footer
    const directory = await tree({ 'alpha.ts': '', 'index.js': expected })
    const output = join(directory, 'index.js')
    await fs.utimes(
      output,
      new Date('2000-01-01T00:00:00Z'),
      new Date('2000-01-01T00:00:00Z'),
    )
    const before = await fs.stat(output)
    const read = vi.spyOn(fs, 'readFile')
    const write = vi.spyOn(fs, 'writeFile')
    generateExports({
      entries: [{ directories: [directory], include: ['*.ts'] }],
    }).start()
    await vi.waitFor(() =>
      expect(
        read.mock.calls.some(([file]) => isSameFilePath(file, output)),
      ).toBe(true),
    )
    await Promise.allSettled(read.mock.results.map((result) => result.value))
    await new Promise(setImmediate)
    expect(write).not.toHaveBeenCalled()
    expect((await fs.stat(output)).mtimeMs).toBe(before.mtimeMs)
  })

  it('characterizes filesystem errors being swallowed without overwriting a directory', async () => {
    const directory = await tree({ 'alpha.ts': '' })
    const output = join(directory, 'index.js')
    await fs.mkdir(output)
    const read = vi.spyOn(fs, 'readFile')
    const generator = generateExports({
      entries: [{ directories: [directory], include: ['*.ts'] }],
    })
    expect(generator.start()).toBeUndefined()
    await vi.waitFor(() =>
      expect(
        read.mock.calls.some(([file]) => isSameFilePath(file, output)),
      ).toBe(true),
    )
    const reads = await Promise.allSettled(
      read.mock.results.map((result) => result.value),
    )
    expect(reads[0].status).toBe('rejected')
    expect((await fs.stat(output)).isDirectory()).toBe(true)
    expect(await fs.readdir(output)).toEqual([])
  })

  it('regenerates from real watcher ready/add/unlink events and applies exclusions to generated exports', async () => {
    const directory = await tree({ 'alpha.ts': '' })
    const watch = vi.spyOn(chokidar, 'watch')
    generateExports({
      watch: true,
      entries: [
        { directories: [directory], include: ['*.ts'], exclude: ['*.spec.ts'] },
      ],
    }).start()
    watchers.push(watch.mock.results[0].value)
    const output = join(directory, 'index.js')
    expect(await content(output)).toContain(
      "export { default as alpha } from './alpha';",
    )
    await fs.writeFile(join(directory, 'beta.ts'), '')
    expect(await content(output, 'default as beta')).toContain("from './beta'")
    await fs.writeFile(join(directory, 'ignored.spec.ts'), '')
    await fs.unlink(join(directory, 'alpha.ts'))
    await vi.waitFor(
      async () => {
        const text = await fs.readFile(output, 'utf8')
        expect(text).not.toContain('default as alpha')
        expect(text).not.toContain('ignored.spec')
        expect(text).toContain('default as beta')
      },
      { timeout: 4000 },
    )
  })

  it('characterizes hyphenated filenames producing invalid export aliases', async () => {
    const directory = await tree({ 'bad-name.ts': 'export default 1' })
    generateExports({
      entries: [
        { directories: [directory], include: ['*.ts'], filename: 'index.ts' },
      ],
    }).start()
    const text = await content(join(directory, 'index.ts'))
    expect(text).toBe(
      header + "export { default as bad-name } from './bad-name';" + footer,
    )
    expect(syntaxErrors(text).length).toBeGreaterThan(0)
  })

  it.fails(
    '[known issue] generated aliases for hyphenated filenames should be valid TypeScript',
    async () => {
      const directory = await tree({ 'bad-name.ts': 'export default 1' })
      generateExports({
        entries: [
          { directories: [directory], include: ['*.ts'], filename: 'index.ts' },
        ],
      }).start()
      const text = await content(join(directory, 'index.ts'))
      expect(syntaxErrors(text)).toHaveLength(0)
    },
  )
})
